#!/usr/bin/env node
// Creates (or re-creates after a database reset) a confirmed LOCAL test user and stores its
// credentials in .local-test-user.json (gitignored). The password is generated here and is
// never printed. The profile is filled in and the demo inbox/calendar is chosen, so signing
// in goes straight to the workspace.
//
//   node scripts/create-test-user.mjs                    create once, reuse afterwards
//   node scripts/create-test-user.mjs --new              always create a new user (new file)
//   node scripts/create-test-user.mjs --file other.json  keep the credentials in another file
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createClient } from "@supabase/supabase-js";
import { parseEnv, readEnvText } from "./env-file.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const fileArg = process.argv.indexOf("--file");
const credentialsFile =
  fileArg > 0 && process.argv[fileArg + 1] ? resolve(process.argv[fileArg + 1]) : join(root, ".local-test-user.json");

// Tolerates a UTF-8 byte-order mark (see env-file.mjs).
const env = Object.fromEntries(parseEnv(readEnvText(join(root, ".env.local"))));
const url = env.SUPABASE_URL;
const secret = env.SUPABASE_SECRET_KEY;
if (!url || !secret) {
  console.error("Missing SUPABASE_URL / SUPABASE_SECRET_KEY in .env.local. Run scripts/write-local-env.mjs first.");
  process.exit(1);
}
if (!/^http:\/\/(127\.0\.0\.1|localhost)(:\d+)?$/.test(url)) {
  console.error(`Refusing to create test users on a non-local Supabase (${url}).`);
  process.exit(1);
}

const admin = createClient(url, secret, { auth: { persistSession: false, autoRefreshToken: false } });
const forceNew = process.argv.includes("--new");

let creds = !forceNew && existsSync(credentialsFile) ? JSON.parse(readFileSync(credentialsFile, "utf8")) : null;
if (!creds?.email || !creds?.password) {
  creds = {
    email: `tester-${randomBytes(4).toString("hex")}@lifeops.test`,
    password: randomBytes(18).toString("base64url"),
  };
}

async function findUser(email) {
  for (let page = 1; page < 20; page += 1) {
    const { data, error } = await admin.auth.admin.listUsers({ page, perPage: 200 });
    if (error) throw error;
    const found = data.users.find((user) => user.email === email);
    if (found) return found;
    if (data.users.length < 200) return null;
  }
  return null;
}

let user = await findUser(creds.email);
let created = false;
if (!user) {
  const { data, error } = await admin.auth.admin.createUser({
    email: creds.email,
    password: creds.password,
    email_confirm: true,
    user_metadata: { name: "Test User" },
  });
  if (error) throw error;
  user = data.user;
  created = true;
}

const { error: profileError } = await admin.from("profiles").upsert({
  id: user.id,
  name: "Test User",
  role: "Student",
  goals: "Finish the research paper, prepare the Acme interview, gym 3x a week, keep evenings free",
  updated_at: new Date().toISOString(),
});
if (profileError) throw profileError;
const { error: demoError } = await admin
  .from("connector_status")
  .upsert({ user_id: user.id, provider: "demo" }, { onConflict: "user_id,provider", ignoreDuplicates: true });
if (demoError) throw demoError;

writeFileSync(
  credentialsFile,
  `${JSON.stringify(
    {
      email: creds.email,
      password: creds.password,
      userId: user.id,
      app: "http://localhost:5190/login",
      note: "Local test user for the local Supabase stack only. Generated by scripts/create-test-user.mjs.",
    },
    null,
    2,
  )}\n`,
  "utf8",
);
console.log(`${created ? "Created" : "Reused"} local test user ${creds.email}; credentials in ${credentialsFile}`);
